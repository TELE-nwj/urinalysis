"""Local editor: scoped design persistence and generation of one Kotlin UI file."""
from http.server import ThreadingHTTPServer, BaseHTTPRequestHandler
from pathlib import Path
import argparse, json, re, threading

HERE = Path(__file__).resolve().parent
CONFIG = HERE / 'ui-design.json'
APP = Path('F:/ESP32/niaio/.worktrees/mobile-app-integration/mobile-app')
TARGET = APP / 'app/src/main/java/com/niaio/mobile/UiDesign.kt'
LOCK = threading.Lock()
LABELS = {'volume':'累计尿量','rate':'实时流速','drops':'累计滴数','elapsed':'有效测量时间',
          'clock':'设备时钟','battery':'电量','storage':'U盘','state':'测量状态','alert':'报警',
          'start':'开始测量','pause':'暂停测量','resume':'继续测量','reset':'复位测量',
          'monitorTab':'实时监测','deviceTab':'设备连接'}
DEFAULT = {'schemaVersion':1,'title':'尿量监测仪','primary':'#1565C0','background':'#FFFFFF','text':'#142E46',
           'numberSp':52,'gapDp':16,'pagePaddingDp':20,'cornerDp':20,
           'metricOrder':['volume','rate','drops','elapsed'],'labels':LABELS}

def validate(data):
    if not isinstance(data,dict) or set(data)!=set(DEFAULT): raise ValueError('设计字段不完整')
    if type(data['schemaVersion']) is not int or data['schemaVersion']!=1: raise ValueError('设计版本不支持')
    def label(value):
        if not isinstance(value,str) or not 1<=len(value)<=48 or any(ord(c)<32 for c in value): raise ValueError('文案须为1至48字，不能包含控制字符')
    label(data['title'])
    for key in ['primary','background','text']:
        if not isinstance(data[key],str) or not re.fullmatch(r'#[0-9a-fA-F]{6}',data[key]): raise ValueError('颜色格式须为#RRGGBB')
    for key,low,high in [('numberSp',32,72),('gapDp',8,32),('pagePaddingDp',12,32),('cornerDp',0,32)]:
        if type(data[key]) is not int or not low<=data[key]<=high: raise ValueError(f'{key}越界')
    if not isinstance(data['metricOrder'],list) or len(data['metricOrder'])!=4 or set(data['metricOrder'])!=set(DEFAULT['metricOrder']): raise ValueError('四个数据项须各保留一次')
    if not isinstance(data['labels'],dict) or set(data['labels'])!=set(LABELS): raise ValueError('文案字段不完整')
    for value in data['labels'].values(): label(value)
    return data

def kotlin(data):
    data=validate(data)
    def quote(value): return json.dumps(value,ensure_ascii=False).replace('$','\\$')
    lines=['package com.niaio.mobile','','// Generated by mobile-ui-editor. Presentation only; no protocol/control logic.','object UiDesign {',f'    const val title = {quote(data["title"])}']
    for key in ['primary','background','text']: lines.append(f'    const val {key}: Long = 0xFF{data[key][1:].upper()}L')
    for key in ['numberSp','gapDp','pagePaddingDp','cornerDp']: lines.append(f'    const val {key} = {data[key]}')
    lines.append('    val metricOrder = listOf('+', '.join(map(quote,data['metricOrder']))+')')
    lines.append('    val labels = mapOf(')
    for key,value in data['labels'].items(): lines.append(f'        {quote(key)} to {quote(value)},')
    lines+=['    )','}','','']
    return '\n'.join(lines)

def read_config(): return validate(json.loads(CONFIG.read_text(encoding='utf8'))) if CONFIG.exists() else json.loads(json.dumps(DEFAULT))
def save_config(data):
    temp=CONFIG.with_suffix('.tmp');temp.write_text(json.dumps(validate(data),ensure_ascii=False,indent=2)+'\n',encoding='utf8');temp.replace(CONFIG)
def apply_config(data):
    if not TARGET.exists(): raise ValueError('安卓设计参数接口尚未就绪，请稍后再同步')
    temp=TARGET.with_suffix('.kt.tmp');temp.write_text(kotlin(data),encoding='utf8');temp.replace(TARGET)

class Handler(BaseHTTPRequestHandler):
    def json_response(self,status,data):
        body=json.dumps(data,ensure_ascii=False).encode();self.send_response(status);self.send_header('Content-Type','application/json; charset=utf-8');self.send_header('Content-Length',str(len(body)));self.send_header('Cache-Control','no-store');self.end_headers();self.wfile.write(body)
    def do_GET(self):
        if self.path=='/api/config':
            with LOCK: self.json_response(200,{'design':read_config(),'androidSource':str(TARGET)})
            return
        assets={'/':'index.html','/index.html':'index.html','/editor.css':'editor.css','/editor.js':'editor.js'}
        name=assets.get(self.path)
        if not name: self.send_error(404);return
        body=(HERE/name).read_bytes();self.send_response(200);self.send_header('Content-Type',{'html':'text/html; charset=utf-8','css':'text/css; charset=utf-8','js':'text/javascript; charset=utf-8'}[name.split('.')[-1]]);self.send_header('Content-Length',str(len(body)));self.send_header('Cache-Control','no-store');self.end_headers();self.wfile.write(body)
    def do_POST(self):
        origin=self.headers.get('Origin');allowed={f'http://127.0.0.1:{self.server.server_port}',f'http://localhost:{self.server.server_port}'}
        if origin and origin not in allowed: self.json_response(403,{'error':'仅允许本地编辑页面'});return
        if self.path not in ['/api/save','/api/apply']: self.send_error(404);return
        try:
            length=int(self.headers.get('Content-Length','0'))
            if not 0<length<=8192: raise ValueError('设计数据长度不正确')
            data=validate(json.loads(self.rfile.read(length)))
            with LOCK:
                save_config(data)
                if self.path=='/api/apply': apply_config(data)
            self.json_response(200,{'ok':True,'message':'已同步到安卓源码；重新构建APK后生效' if self.path=='/api/apply' else '设计已保存到本地','design':data})
        except (ValueError,TypeError,OSError) as error: self.json_response(400,{'error':str(error)})
    def log_message(self,*args): pass

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--port',type=int,default=8768);args=parser.parse_args()
    if not CONFIG.exists(): save_config(DEFAULT)
    server=ThreadingHTTPServer(('127.0.0.1',args.port),Handler)
    print(f'UI editor http://127.0.0.1:{args.port}',flush=True)
    server.serve_forever()
